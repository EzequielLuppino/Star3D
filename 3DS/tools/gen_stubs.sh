#!/bin/bash
# Regenerate stubs/sdk_stubs.c from the linker's undefined references.
#
#   bash tools/gen_stubs.sh
#
# Builds, collects every "undefined reference to `X'" from the link, adds the
# names to stubs/sdk_stubs.list and regenerates stubs/sdk_stubs.c with a weak
# logging stub for each. Real implementations override the weak stubs, so the
# list only needs to grow. Data symbols (variables) must be defined by hand in
# port/ instead; list them in DATA_SYMBOLS so they are never stubbed as code.
cd "$(dirname "$0")/.." || exit 1

LIST=stubs/sdk_stubs.list
OUT=stubs/sdk_stubs.c
LOG=build/tmp/gen_stubs.log
DATA_SYMBOLS="GXNtsc480IntDf"

mkdir -p build/tmp
touch $LIST
bash run_test.sh > $LOG 2>&1

grep -oE "undefined reference to \`[^']+'" $LOG | sed -E "s/.*\`//; s/'$//" | sort -u > build/tmp/undef_new.txt
for sym in $DATA_SYMBOLS; do
    if grep -qx "$sym" build/tmp/undef_new.txt; then
        echo "error: data symbol $sym is undefined; define it in port/" >&2
    fi
    sed -i "/^$sym\$/d" build/tmp/undef_new.txt
done

new=$(comm -13 <(sort -u $LIST) build/tmp/undef_new.txt | wc -l)
sort -u $LIST build/tmp/undef_new.txt -o $LIST
echo "added $new symbols, $(wc -l < $LIST) stubs total"

{
    echo "// GENERATED by tools/gen_stubs.sh from stubs/sdk_stubs.list - do not edit."
    echo "//"
    echo "// Weak placeholders for SDK/port functions the game calls but the 3DS layer"
    echo "// does not implement yet. Each logs its first call and counts calls in the"
    echo "// profiler (\"stub.<name>\"). Implementing a function anywhere in port/"
    echo "// overrides its stub. Dolphin headers are deliberately not included so the"
    echo "// generic signature does not conflict with the real prototypes."
    echo
    echo "#include \"log.h\""
    echo "#include \"profiler.h\""
    echo "#include \"watchdog.h\""
    echo
    echo "#define STUB(name) \\"
    echo "    __attribute__((weak)) unsigned int name(void) { \\"
    echo "        LOG_ONCE(LOG_LEVEL_WARN, \"stub\", \"%s called\", #name); \\"
    echo "        PROF_COUNT(\"stub.\" #name, 1); \\"
    echo "        g_last_stub = #name; \\"
    echo "        g_stub_calls++; \\"
    echo "        return 0; \\"
    echo "    }"
    prev=""
    while read -r sym; do
        [ -z "$sym" ] && continue
        group=$(echo "$sym" | sed -E 's/^([a-z]+|[A-Z][A-Z]+[a-z]?)([A-Z].*)?$/\1/')
        if [ "$group" != "$prev" ]; then
            echo
            prev=$group
        fi
        echo "STUB($sym)"
    done < $LIST
} > $OUT

echo "wrote $OUT"
